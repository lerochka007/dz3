# функция считает среднее арифметическое трёх оценок
def average_grade(a, b, c):
    # складываем все оценки и делим на 3
    return (a + b + c) / 3

# фнкция возвращает сообщение в зависимости от среднего балла
def grade_message(average):
    # если средний балл 4.5 и выше - отлично
    if average >= 4.5:
        return "Отлично"
    # если от 3.5 до меньше 4.5 - хорошо
    elif average >= 3.5:
        return "Хорошо"
    # во всех остальных случаях нужно повторить материал
    else:
        return "Нужно повторить материал"

# сначала считаю среднее для оценок 5, 4, 5
avg1 = average_grade(5, 4, 5)
# получаю сообщение по этому среднему
msg1 = grade_message(avg1)
# вывожу результат
print(avg1, msg1)

# теперь то же самое для оценок 3, 4, 3
avg2 = average_grade(3, 4, 3)
msg2 = grade_message(avg2)
print(avg2, msg2)
